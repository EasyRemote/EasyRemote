"""Pipeline: EAL compilation (grammar-pinned), validation, mission calls."""

import pytest
from test_client import IDENTITY, FakeTransport, ok_response  # shared fakes

from easyremote.client import Client
from easyremote.errors import InvalidArgument
from easyremote.pipeline import MissionRun, Pipeline, StepOutput


def make_client(responses=None):
    transport = FakeTransport(responses=responses)
    return Client(transport=transport, identity=IDENTITY), transport


def test_two_step_mission_compiles_to_pinned_eal():
    pipe = Pipeline("nightly-report")
    fetch = pipe.step("teamA.fetch_sales", quarter="Q2", timeout=60)
    pipe.step("er.summarize", rows=fetch.output, on_failure="retry", retries=2)

    eal = pipe.to_eal()
    assert (
        'mission "nightly-report" {\n'
        '  let fetch_sales = call "teamA.fetch_sales"'
        ' with { quarter = "Q2" } timeout 60\n'
        '  let summarize = call "er.summarize"'
        " with { rows = fetch_sales.output } retries 2 on_failure retry\n"
        "}"
    ) in eal
    assert eal.startswith("// generated by easyremote")


def test_on_target_and_bool_int_rendering():
    pipe = Pipeline("p")
    pipe.step("design", on="claude", prompt="go", fast=True, n=3)
    eal = pipe.to_eal()
    assert 'call "design" on "claude"' in eal
    assert "fast = true" in eal
    assert "n = 3" in eal


