def test_alias_deduplication():
    pipe = Pipeline("p")
    first = pipe.step("er.fn", a=1)
    second = pipe.step("er.fn", a=2)
    assert first.alias == "fn"
    assert second.alias == "fn_2"


def test_non_scalar_field_rejected_with_guidance():
    pipe = Pipeline("p")
