def test_created_by_header_uses_identity():
    client, _ = make_client()
    pipe = Pipeline("p", client=client)
    pipe.step("er.fn", a=1)
    assert "// created_by: easynet:///r/acme/device/dev-a" in pipe.to_eal()


def test_run_submits_source_to_mission_run():
    client, transport = make_client(
        responses=[
            ok_response(
                {"ok": True, "run_id": "run-1", "run_dir": "/tmp/r", "outputs": {}}
            )
        ]
    )
    pipe = Pipeline("nightly", client=client)
    pipe.step("er.fn", a=1)

    run = pipe.run()
    wire = transport.invocations[0]
    assert transport.carriers == ["unary"]
    assert (
        wire["descriptor_ref"]
        == "easynet:///r/acme/ability/device.dev-a.mission.run@1.0.0"
    )
    assert wire["args"]["label"] == "nightly"
    assert 'mission "nightly"' in wire["args"]["source"]
    assert run.run_id == "run-1"


def test_track_and_cancel_use_run_id():
    client, transport = make_client(
        responses=[
            ok_response({"ok": True, "run_id": "run-9"}),
            ok_response({"state": "running"}),
            ok_response({"cancelled": True}),
        ]
    )
    pipe = Pipeline("p", client=client)
    pipe.step("er.fn")
    run = pipe.run()

    assert run.track() == {"state": "running"}
    run.cancel()
    assert transport.carriers == ["unary", "unary", "unary"]
    assert (
        transport.invocations[1]["descriptor_ref"]
        == "easynet:///r/acme/ability/device.dev-a.mission.track@1.0.0"
    )
    assert transport.invocations[1]["args"] == {"run_id": "run-9"}
    assert (
        transport.invocations[2]["descriptor_ref"]
        == "easynet:///r/acme/ability/device.dev-a.mission.cancel@1.0.0"
    )


def test_mission_run_exposes_response_fields():
    client, _ = make_client()
    run = MissionRun(
        client.missions,
        {"run_id": "r", "run_dir": "/d", "outputs": {"x": 1}},
    )
    assert run.run_dir == "/d"
    assert run.outputs == {"x": 1}
